def get_analysis_prompt(ocr_text: str) -> str:
    """获取分析提示词"""
    return f"""分析以下题目内容：

{ocr_text}

任务：
1. 提取完整的题目内容（只包含印刷体，不包含手写体）
   - **保留括号和横线**：题目中的括号（如：( )、（））和横线（如：______、_____）必须保留，不要用答案填充
   - **去掉手写答案**：学生写在括号或横线上的手写答案必须去掉，只保留空的括号或横线
   - **还原题目本来的样子**：题目应该看起来像原题，包含括号、横线等占位符
   - 示例：如果题目是"这个三角形是(锐角)三角形"，应该还原为"这个三角形是( )三角形"
2. 提取学生手写答案（只包含手写体，不包含印刷体）
   - **仔细识别所有手写内容**：不要遗漏任何学生手写的答案
   - **识别要完整**：不要只识别部分内容，例如"锐角"不要只识别成"锐"
   - **区分笔迹颜色**：
     - 如果手写体有黑色和红色，黑色是学生的答案，红色是老师的订正
     - **忽略红色笔迹**：只识别黑色笔迹作为学生答案
     - 示例：如果学生写的是"19"，老师用红色笔订正为"190"，学生答案应该是"19"，而不是"190"
   - **学生答案必须是图片中实际手写的内容**：不要用正确答案替代学生答案
   - **学生答案可能和正确答案不同**：这是正常的，因为学生可能做错了
   - **如果没有识别到手写答案，student_answer 必须为空字符串**：绝对不能用正确答案填充
   - **绝对禁止**：在没有手写答案的情况下，用正确答案填充 student_answer
   - 如果有多个填空，用逗号分隔所有学生答案
   - 示例：如果学生手写的是"(锐角)"和"(1)"，student_answer应该是"锐角，1"，而不是"锐，1"或"等腰，1"
   - 示例：如果没有识别到手写内容，student_answer应该是""，而不是正确答案
3. **基于题目内容准确计算或推理出正确答案**
     - 仔细分析题目要求，按照正确的运算顺序和计算方法进行计算
     - **正确答案必须完全独立推理，绝对不能受学生答案影响**
     - **对于几何题，要根据几何定义和性质推理**：
       - **三角形类型判断**：
         - 根据边的长度关系：两边相等→等腰三角形，三边相等→等边三角形，三边不等→不等边三角形
         - 根据角度：最大角<90°→锐角三角形，最大角=90°→直角三角形，最大角>90°→钝角三角形
       - **重要**：题目问的是什么就答什么，不要混淆
         - 如果题目问"这个三角形是什么三角形"，要根据题目条件判断
         - 示例：三条边分别为4厘米、3厘米、4厘米，有两边相等，所以是等腰三角形（正确答案：等腰）
         - 不要答非所问：题目问类型，不要答角度
     - 如果有多个填空，用逗号分隔所有正确答案
     - 示例：正确答案应该是"等腰，1"，而不是"锐角，1"
4. 判断学生答案是否正确
   - 逐个对比每个填空的答案
   - 只要有一个填空错误，is_wrong就为true
  5. 如果错误，分析错误原因
  6. **最终验证步骤（非常重要）**：
   - 检查 student_answer 和 correct_answer 是否相同
   - 如果相同，说明识别有问题，需要进一步判断：
     a. 如果 correct_answer 是基于题目推理的正确答案，那么 student_answer 必须置空（说明没有识别到手写答案）
     b. 如果 correct_answer 本身就是错的，需要重新分析题目，得出正确的 correct_answer
   - **绝对禁止**：student_answer 和 correct_answer 相同的情况出现

**重要：必须从以下5个错误类型中选择一个（只能返回中文）：**
- **计算错误**：加减乘除算错了、进位借位错了、小数点点错了、抄错数字、写错符号等
- **概念不清**：记错公式、理解错意思、混淆相似概念、用错公式等
- **审题错误**：没看清题目、看错数字、答非所问、漏看条件、理解错题意等
- **粗心大意**：漏写单位、漏写答案、写错位置、忘记做题、抄错题目等
- **无错误**：学生答案正确，没有错误

**重要计算要求：**
- 对于数学计算题，必须按照正确的运算顺序（先乘除后加减，有括号先算括号内）进行计算
- **关于"几个几"的题目，要特别注意理解题意**：
  - "2个30相乘" = 30 × 30 = 900（两个30相乘，不是2×30）
  - "3个25相加" = 25 + 25 + 25 = 75（三个25相加，不是3×25）
  - "4个125相乘" = 125 × 125 × 125 × 125（四个125相乘）
  - **这是小学数学中常见的题目类型，"几个几"表示的是乘法或连加的意义**
  - **学生作答时可能会错误地写成 2×30 而不是 30×30，这时应该判断为审题错误**
- **关于"除"和"除以"的区别（非常重要）**：
  - "A 除 B" 或 "用A去除B" = B ÷ A（A是除数，B是被除数）
  - "A 除以 B" 或 "用A除以B" = A ÷ B（A是被除数，B是除数）
  - 示例："用30去除900" = 900 ÷ 30，"用30除以900" = 30 ÷ 900
  - **这是小学数学中容易混淆的概念，必须准确理解**
- **优先使用巧算方法**：
  - 观察题目特点，寻找简算机会
  - 除法分配律：a÷c + b÷c = (a+b)÷c，a÷c - b÷c = (a-b)÷c
  - 示例：143÷125-43÷125+25÷125 = (143-43+25)÷125 = 125÷125 = 1
  - 乘法分配律：a×c + b×c = (a+b)×c，a×c - b×c = (a-b)×c
  - 凑整法：寻找能凑成整十、整百的数
  - 提取公因数：a×b + a×c = a×(b+c)
- 计算过程要仔细，避免出现计算错误
- **确保correct_answer字段中的答案与推理步骤中的计算结果完全一致**
- 不要猜测答案，必须基于题目内容和正确的计算方法得出结论

**语言要求：**
- 对于英语学科的题目：
  - 题目内容和答案可以保留英文
  - 但**分析内容（错误原因、解析、推理步骤等）必须使用中文**
- 对于其他学科的题目：
  - 所有内容都使用中文

**学科识别要求：**
- 数学：包含数字、符号、几何图形、计算等内容的题目
- 语文：包含汉字、词语、句子、阅读理解等内容的题目
- 英语：包含英文单词、句子、阅读理解等内容的题目
- 必须从以上三个学科中选择一个，不能返回 'unknown'

输出JSON格式：
{{
  "question_text": "完整题目内容（只包含印刷体，括号和横线保持原样，不要填充）",
  "student_answer": "学生答案（只包含手写体，多个答案用逗号分隔）",
  "correct_answer": "正确答案（基于题目推理得出，多个答案用逗号分隔）",
  "is_wrong": true/false,
  "error_type": "calculation/concept/reading/careless/none",
  "error_reason": "错误原因",
  "explanation": "题目解析",
  "reasoning_steps": "推理步骤（分步骤展示如何从题目推导出正确答案）",
  "subject": "math/chinese/english",
  "difficulty": "easy/medium/hard"
}}

重要要求：
- **question_text 必须保持题干干净**：括号和横线必须保留，不要填充任何内容
- **student_answer 必须准确识别所有手写答案**：不要遗漏，多个答案用逗号分隔
- **student_answer 必须是图片中实际手写的内容**：绝对不能用正确答案替代学生答案
- **如果没有识别到手写答案，student_answer 必须为空字符串**：绝对不能用正确答案填充
- **绝对禁止**：在没有手写答案的情况下，用正确答案填充 student_answer
- **correct_answer 必须是基于题目内容推理出来的客观正确答案**：多个答案用逗号分隔
- correct_answer 不能受到 student_answer 的影响，必须独立推理
- 如果学生答案明显错误（如把"等腰"写成"锐角"），正确答案应该是"等腰"，而不是"锐角"
- **student_answer 和 correct_answer 可能不同**：这是正常的，因为学生可能做错了
- **对于英语题目，要特别注意大小写问题**：
  - 专有名词（如人名、地名、星期、月份）首字母大写
  - 普通名词（如 birthday, apple, book）应该小写
  - 句首字母大写，其他小写
  - 如果学生答案中存在大小写错误，必须在 correct_answer 中纠正

只输出JSON。"""


def get_similar_question_prompt(question_text: str, error_type: str, error_reason: str, grade: str = '') -> str:
    """获取生成类似题目的提示词"""
    grade_context = ""
    if grade:
        grade_labels = {
            '1': '一年级', '2': '二年级', '3': '三年级',
            '4': '四年级', '5': '五年级', '6': '六年级'
        }
        grade_label = grade_labels.get(str(grade), f'{grade}年级')
        grade_context = f"学生年级：{grade_label}\n"
    
    return f"""你是一位经验丰富的小学老师，请根据以下错题信息，设计一道有针对性的练习题：

{grade_context}【原题】{question_text}
【错误类型】{error_type}
【错误原因】{error_reason}

**设计思路（不要输出，仅供内部思考）：**
1. **分析考点**：这道题真正考查的核心知识点是什么？（不是表面形式，而是底层能力）
2. **反推学生思路**：从学生的错误答案出发，推测学生是怎么想的？哪里想错了？
3. **定位薄弱点**：学生的薄弱点具体在哪里？是概念理解、运算技能、还是审题习惯？
4. **针对性设计**：新题目应该精准打击这个薄弱点，而不是简单换数字

**出题要求：**
1. **考查同一个核心知识点**，但题目形式要有所变化（不能只是换数字）
2. **精准针对学生的薄弱点**：如果学生是审题错误，新题要设计容易看错的条件；如果是概念不清，新题要从另一个角度考查同一个概念
3. **难度略高于原题**：让学生需要多思考一步，但仍在能力范围内
4. **设置合理的干扰项**：如果是选择题，干扰项应该是学生容易犯的典型错误（基于错误原因设计）
5. **避免机械重复**：不要只是把原题的数字换一下，要换情境、换角度、换形式
6. **确保计算正确**：数学题的答案必须经过验证
7. **使用该年级学生能理解的知识和方法**

**变化策略（至少使用其中2种）：**
- 换情境：把题目背景换成学生熟悉的生活场景
- 换角度：从正向考查改为逆向考查，或反之
- 换形式：选择题改填空，或计算改判断
- 增加一步：在原题基础上增加一个需要多思考的环节
- 设置陷阱：在容易出错的地方设置合理干扰

输出JSON格式：
{{
  "question_text": "新题目内容",
  "options": [{{"key": "A", "text": "选项A"}}],
  "correct_answer": "正确答案",
  "explanation": "解题思路（50字以内）",
  "design_reason": "为什么这样设计（说明针对了学生的哪个薄弱点，50字以内）"
}}

只输出JSON，不要其他内容。"""


